// Renders docs/evidence/session-2/authority-matrix.md from AUTHORITY_MATRIX and
// the statuses observed by tests/integration/openbao/authority.test.ts
// (docs/evidence/session-2/authority-matrix.json).
// With --check it writes nothing and exits 1 when the file is stale, or when an
// observation is missing or differs from its expectation.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  AUTHORITY_ACTIONS,
  AUTHORITY_MATRIX,
  COLUMNS,
  IDENTITIES,
  ROOT_CONTROLS,
  cellColumn,
  cellKey,
  controlOf,
  type AuthorityCell,
  type Column,
} from "@mykey/openbao";
import { format, resolveConfig } from "prettier";

const EVIDENCE = resolve(import.meta.dirname, "../docs/evidence/session-2");
export const MATRIX_FILE = resolve(EVIDENCE, "authority-matrix.md");
export const OBSERVATIONS_FILE = resolve(EVIDENCE, "authority-matrix.json");

export interface Observations {
  openbao: string;
  cells: Record<string, number>;
  inline: Record<string, number>;
  controls: Record<string, { by: string; status: number }>;
}

const COLUMN_TITLES: Record<Column, string> = {
  own: "own",
  other_environment: "other env",
  other_organization: "other org",
  other_organization_path: "other org (path)",
  root: "root",
};

function isAllowed(status: number): boolean {
  return status === 200 || status === 204;
}

function matches(cell: AuthorityCell, status: number): boolean {
  return cell.expect === "allow" ? isAllowed(status) : status === (cell.expectStatus ?? 403);
}

/** Every reason why the observations do not prove the matrix; empty when they do. */
export function problems(observations: Observations): string[] {
  const found: string[] = [];
  const keys = new Set(AUTHORITY_MATRIX.map(cellKey));
  for (const key of Object.keys(observations.cells)) {
    if (!keys.has(key)) found.push(`observation without a cell: ${key}`);
  }
  for (const cell of AUTHORITY_MATRIX) {
    const status = observations.cells[cellKey(cell)];
    if (status === undefined) found.push(`no observation: ${cellKey(cell)}`);
    else if (!matches(cell, status)) found.push(`${cellKey(cell)}: observed ${status}`);
    if (cell.identity === "runtime" && observations.inline[cellKey(cell)] === undefined) {
      found.push(`no inline observation: ${cellKey(cell)}`);
    }
    if (cell.expect === "deny") {
      const group = `${cell.action} ${cellColumn(cell)}`;
      const control = observations.controls[group];
      const declared = controlOf(cell);
      const wanted =
        declared.by === "root" && declared.control !== undefined
          ? declared.control.status
          : undefined;
      if (control === undefined) found.push(`no control: ${group}`);
      else if (wanted === undefined ? !isAllowed(control.status) : control.status !== wanted) {
        found.push(`control ${group}: observed ${control.status}`);
      }
    }
  }
  return [...new Set(found)];
}

function code(text: string): string {
  return `\`${text}\``;
}

export function renderMarkdown(observations: Observations): string {
  const reasons: string[] = [];
  const footnote = (reason: string | undefined): string => {
    if (reason === undefined) return "";
    if (!reasons.includes(reason)) reasons.push(reason);
    return ` [${reasons.indexOf(reason) + 1}]`;
  };
  const cellText = (cell: AuthorityCell | undefined): string => {
    if (cell === undefined) return "—";
    const status = observations.cells[cellKey(cell)];
    const shown = status === undefined ? "?" : String(status);
    const text = `${cell.expect} ${shown}${footnote(cell.reason)}`;
    return status !== undefined && matches(cell, status) ? text : `**MISMATCH** ${text}`;
  };

  const lines: string[] = [
    `# Authority matrix — OpenBao ${observations.openbao}`,
    "",
    "Generated by `node scripts/authority-matrix.ts` from `AUTHORITY_MATRIX` (`packages/openbao/src/authority.ts`) and the statuses that `tests/integration/openbao/authority.test.ts` observed with real tokens (`authority-matrix.json`). Do not edit by hand; `pnpm run authority:check` fails when this file is stale.",
    "",
    "Columns: **own** — organization A, environment 1 (the machine token's own environment); **other env** — organization A, environment 2; **other org** — organization B through the `X-Vault-Namespace` header; **other org (path)** — the root namespace with the path prefixed `org-<B>/`; **root** — the root namespace. `—`: the request has no meaning there and is not sent.",
    "",
    "Each cell is the expectation and the observed HTTP status. `allow` means 200 or 204; `deny` means exactly 403 unless a numbered note says why OpenBao answers before it evaluates any policy. Every denial has a control: the same request by an allowed identity, or by the root token (section Controls).",
    "",
  ];

  for (const identity of IDENTITIES) {
    lines.push(`## ${identity}`, "");
    lines.push(`| Action | Request | ${COLUMNS.map((c) => COLUMN_TITLES[c]).join(" | ")} |`);
    lines.push(`| --- | --- | ${COLUMNS.map(() => "---").join(" | ")} |`);
    for (const action of AUTHORITY_ACTIONS) {
      const cells = AUTHORITY_MATRIX.filter((c) => c.identity === identity && c.action === action);
      const own = cells.find((c) => c.target === "own");
      if (own === undefined) throw new Error(`no own cell: ${identity} ${action}`);
      const request = `${own.request.method} ${own.request.path}`;
      const row = COLUMNS.map((column) => cellText(cells.find((c) => cellColumn(c) === column)));
      lines.push(`| ${action} | ${code(request)} | ${row.join(" | ")} |`);
    }
    lines.push("");
  }

  const runtime = AUTHORITY_MATRIX.filter((cell) => cell.identity === "runtime");
  const differences = runtime.filter(
    (cell) => observations.inline[cellKey(cell)] !== observations.cells[cellKey(cell)],
  );
  lines.push(
    "## PO-3: runtime row with inline authentication",
    "",
    `The ${runtime.length} runtime cells were sent again with inline AppRole authentication (\`X-Vault-Inline-Auth-*\` headers, no token). ${runtime.length - differences.length} answered exactly as with the login token. The differences:`,
    "",
    "| Cell | Login token | Inline |",
    "| --- | --- | --- |",
    ...differences.map(
      (cell) =>
        `| ${cellKey(cell)} | ${String(observations.cells[cellKey(cell)])} | ${String(observations.inline[cellKey(cell)])} |`,
    ),
    "",
    "## Controls",
    "",
    "| Request | Column | Control | Observed |",
    "| --- | --- | --- | --- |",
  );
  for (const [group, control] of Object.entries(observations.controls)) {
    const [action, column] = group.split(" ") as [string, Column];
    const declared = ROOT_CONTROLS.find((c) => c.action === action && c.column === column);
    lines.push(
      `| ${action} | ${COLUMN_TITLES[column]} | ${control.by} | ${control.status}${footnote(declared?.reason)} |`,
    );
  }
  lines.push("", "## Notes", "");
  reasons.forEach((reason, index) => lines.push(`${index + 1}. ${reason}`));
  lines.push("");
  return lines.join("\n");
}

async function formatted(text: string): Promise<string> {
  const options = (await resolveConfig(MATRIX_FILE)) ?? {};
  return format(text, { ...options, filepath: MATRIX_FILE });
}

if (import.meta.main) {
  const read = JSON.parse(readFileSync(OBSERVATIONS_FILE, "utf8")) as Partial<Observations>;
  const observations: Observations = {
    openbao: read.openbao ?? "?",
    cells: read.cells ?? {},
    inline: read.inline ?? {},
    controls: read.controls ?? {},
  };
  const found = problems(observations);
  const text = await formatted(renderMarkdown(observations));
  if (process.argv.includes("--check")) {
    let committed: string;
    try {
      committed = readFileSync(MATRIX_FILE, "utf8");
    } catch {
      committed = "";
    }
    if (committed !== text) found.push("authority-matrix.md is out of date");
    if (found.length > 0) {
      console.error(`authority matrix: ${found.length} problem(s)`);
      for (const line of found.slice(0, 20)) console.error(`  ${line}`);
      console.error(
        "Run: pnpm run test:integration (observations), then node scripts/authority-matrix.ts",
      );
      process.exit(1);
    }
    console.log(`authority matrix: ${AUTHORITY_MATRIX.length} cells current and proven.`);
  } else {
    writeFileSync(MATRIX_FILE, text);
    console.log(`Wrote ${MATRIX_FILE} (${AUTHORITY_MATRIX.length} cells).`);
    if (found.length > 0) {
      console.error(`authority matrix: ${found.length} problem(s)`);
      for (const line of found.slice(0, 20)) console.error(`  ${line}`);
      process.exit(1);
    }
  }
}
