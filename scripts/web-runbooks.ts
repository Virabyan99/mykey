// Run 9.0 Task E (P-160): the two consumer runbooks as a module of the
// workspace, so "Connect an application" shows their own commands. The API
// image builds the workspace from apps/web and three named files only
// (apps/api/Dockerfile, stage `web`), so the runbooks travel inside
// apps/web as this generated module; tests/unit/web/connect-commands.test.ts
// fails when it is not equal to the files.
//
//   node scripts/web-runbooks.ts          write apps/web/src/connect/runbooks.ts
//   node scripts/web-runbooks.ts --check  exit 1 when it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/web/src/connect/runbooks.ts");

const read = (file: string): string =>
  readFileSync(join(ROOT, "docs/runbooks", file), "utf8").replaceAll("\r\n", "\n");

export function runbooksModule(): string {
  return [
    "// Generated by scripts/web-runbooks.ts from docs/runbooks: do not edit.",
    "// connect-commands.test.ts fails when this is not equal to the runbooks.",
    `export const CONSUMER_LOCAL = ${JSON.stringify(read("consumer-local.md"))};`,
    `export const CONSUMER_DEPLOY = ${JSON.stringify(read("consumer-deploy.md"))};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const wanted = runbooksModule();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8").replaceAll("\r\n", "\n");
    if (current !== wanted) {
      console.error("web-runbooks: stale; run node scripts/web-runbooks.ts");
      process.exit(1);
    }
    console.log("web-runbooks: current");
  } else {
    writeFileSync(OUT, wanted);
    console.log(`web-runbooks: wrote ${OUT}`);
  }
}
